const SORTED_TERMS = [...TERM_MAP].sort((a, b) => b[0].length - a[0].length);
const LOOKUP = new Map<string, string>(SORTED_TERMS);

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

const TERM_PATTERN = new RegExp(SORTED_TERMS.map(([k]) => escapeRegex(k)).join("|"), "g");
const INFO_PATTERN = /信息(?!素)/g;
const PROTECTED_SPAN = /```[\s\S]*?```|`[^`\n]+`|https?:\/\/[^\s)>"'<>]+/g;

/**
 * Normalizes unambiguous Mainland China terms to Taiwan Traditional Chinese while leaving
 * fenced code blocks, inline code spans, and URLs completely untouched.
 */
export function normalizeTaiwanTerms(text: string): string {
  if (!text) return text;
  const preserved: string[] = [];
  const masked = text.replace(PROTECTED_SPAN, (match) => {
    const token = `\uE000${preserved.length}\uE001`;
    preserved.push(match);
    return token;
  });

  const normalized = masked
    .replace(TERM_PATTERN, (hit) => LOOKUP.get(hit) ?? hit)
    .replace(INFO_PATTERN, "資訊");

  if (preserved.length === 0) return normalized;
  return normalized.replace(/\uE000(\d+)\uE001/g, (_, idx) => preserved[Number(idx)] ?? "");
}
